import json
import secrets
import time
from pathlib import Path

import jwt
from cryptography.hazmat.primitives.asymmetric import ec
from jwt.algorithms import ECAlgorithm

API_KEY_LIFETIME = 10 * 365 * 24 * 3600


def new_signing_key() -> dict:
    """A fresh private ES256 JWK with its own kid."""
    key = ec.generate_private_key(ec.SECP256R1())
    return json.loads(ECAlgorithm.to_jwk(key)) | {
        "kid": secrets.token_hex(8),
        "alg": "ES256",
        "use": "sig",
    }


def public_jwk(private_jwk: dict) -> dict:
    return {k: v for k, v in private_jwk.items() if k != "d"}


def api_key(private_jwk: dict, role: str) -> str:
    now = int(time.time())
    claims = {"iss": "kilnbase", "role": role, "iat": now, "exp": now + API_KEY_LIFETIME}
    key = jwt.PyJWK.from_dict(private_jwk).key
    return jwt.encode(claims, key, algorithm="ES256", headers={"kid": private_jwk["kid"]})


def quoted_json(value: dict) -> str:
    # Single-quoted so docker compose reads the JSON literally.
    return f"'{json.dumps(value, separators=(',', ':'))}'"


def new_s3_keys() -> dict[str, str]:
    return {
        "KILNBASE_S3_ACCESS_KEY_ID": "kb_" + secrets.token_hex(8),
        "KILNBASE_S3_SECRET_ACCESS_KEY": secrets.token_urlsafe(30),  # 40 characters
    }


def generate_env() -> str:
    private_jwk = new_signing_key()
    values = {
        "POSTGRES_PASSWORD": secrets.token_urlsafe(32),
        "KILNBASE_AUTHENTICATOR_PASSWORD": secrets.token_urlsafe(32),
        "KILNBASE_STORAGE_SIGNING_KEY": secrets.token_urlsafe(48),
        "KILNBASE_JWT_PRIVATE_JWK": quoted_json(private_jwk),
        "KILNBASE_JWKS": quoted_json({"keys": [public_jwk(private_jwk)]}),
        "KILNBASE_ANON_KEY": api_key(private_jwk, "anon"),
        "KILNBASE_SERVICE_ROLE_KEY": api_key(private_jwk, "service_role"),
        **new_s3_keys(),
    }
    header = (
        "# Generated by `kilnbase init`. Keep this file secret and out of version control.\n"
        "# KILNBASE_SERVICE_ROLE_KEY bypasses row level security: never ship it to clients.\n"
        "# The KILNBASE_S3_* key pair acts as service_role over the S3 API: servers only.\n"
    )
    return header + "".join(f"{k}={v}\n" for k, v in values.items())


def run(path: Path, force: bool) -> int:
    # Overwriting replaces the signing key and DB password, locking out existing data and tokens.
    if path.exists() and not force:
        print(f"{path} already exists; refusing to overwrite existing secrets (use --force).")
        return 1
    path.write_text(generate_env(), encoding="utf-8", newline="\n")
    try:
        path.chmod(0o600)
    except OSError:
        pass  # shortcut: no-op on Windows ACLs, fine for local dev; servers run Linux
    print(f"Wrote {path}. Start with: docker compose up -d")
    return 0
