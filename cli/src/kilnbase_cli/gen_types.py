import json
import subprocess
import sys
from pathlib import Path

from .doctor import query_db

# One round trip; `:'schema'` is quoted by psql. Only relations an API role can read are listed,
# since everything else is invisible to `/rest/v1` anyway.
META_SQL = """
with rels as (
    select c.oid, c.relname, c.relkind from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = :'schema' and c.relkind in ('r', 'p', 'v', 'm')
       and (has_table_privilege('anon', c.oid, 'SELECT')
            or has_table_privilege('authenticated', c.oid, 'SELECT'))
),
cols as (
    select a.attrelid, a.attnum, json_build_object(
               'name', a.attname,
               'type', st.typname,
               'enum', st.typtype = 'e' and st.typnamespace = :'schema'::regnamespace,
               'array', et.oid is not null,
               'nullable', not a.attnotnull,
               'default', a.atthasdef or a.attidentity <> '',
               'generated', a.attgenerated <> '') as col
      from pg_attribute a
      join pg_type t on t.oid = a.atttypid
      -- domains resolve to their base type, arrays to their element type
      join pg_type bt on bt.oid = coalesce(nullif(t.typbasetype, 0), t.oid)
      left join pg_type et on et.oid = bt.typelem and bt.typcategory = 'A'
      join pg_type st on st.oid = coalesce(et.oid, bt.oid)
     where a.attrelid in (select oid from rels) and a.attnum > 0 and not a.attisdropped
)
select json_build_object(
    'relations', coalesce((
        select json_agg(json_build_object(
                   'name', r.relname,
                   'view', r.relkind in ('v', 'm'),
                   'columns', coalesce((select json_agg(col order by attnum) from cols
                                         where attrelid = r.oid), '[]'))
                 order by r.relname)
          from rels r), '[]'),
    'enums', coalesce((
        select json_object_agg(t.typname, (select json_agg(e.enumlabel order by e.enumsortorder)
                                             from pg_enum e where e.enumtypid = t.oid))
          from pg_type t
         where t.typtype = 'e' and t.typnamespace = :'schema'::regnamespace), '{}'));
"""

NUMBER = {"int2", "int4", "int8", "float4", "float8", "numeric", "oid"}
JSON_TYPE = (
    "export type Json =\n"
    "  | string\n  | number\n  | boolean\n  | null\n"
    "  | { [key: string]: Json | undefined }\n  | Json[];\n"
)


def ts_type(col: dict, enums: dict[str, list[str]]) -> str:
    name = col["type"]
    if col["enum"]:
        base = " | ".join(json.dumps(label) for label in enums[name])
    elif name in NUMBER:
        base = "number"
    elif name == "bool":
        base = "boolean"
    elif name in ("json", "jsonb"):
        base = "Json"
    else:
        # PostgREST sends dates, uuids, intervals, text and the rest as JSON strings.
        base = "string"
    if col["array"]:
        base = f"({base})[]" if " " in base else f"{base}[]"
    return f"{base} | null" if col["nullable"] else base


def fields(columns: list[dict], enums: dict, mode: str) -> str:
    lines = []
    for c in columns:
        key = json.dumps(c["name"])
        if mode == "Row":
            lines.append(f"          {key}: {ts_type(c, enums)};")
        elif c["generated"]:
            lines.append(f"          {key}?: never;")
        else:
            optional = mode == "Update" or c["nullable"] or c["default"]
            lines.append(f"          {key}{'?' if optional else ''}: {ts_type(c, enums)};")
    return "{\n" + "\n".join(lines) + ("\n" if lines else "") + "        }"


def render(meta: dict, schema: str = "public") -> str:
    enums = meta["enums"]
    tables, views = [], []
    for rel in meta["relations"]:
        modes = ["Row"] if rel["view"] else ["Row", "Insert", "Update"]
        body = "\n".join(f"        {m}: {fields(rel['columns'], enums, m)};" for m in modes)
        (views if rel["view"] else tables).append(
            f"      {json.dumps(rel['name'])}: {{\n{body}\n      }};"
        )
    enum_lines = [
        f"      {json.dumps(name)}: {' | '.join(json.dumps(v) for v in labels)};"
        for name, labels in sorted(enums.items())
    ]

    def block(name: str, items: list[str]) -> str:
        return f"    {name}: {{\n" + "".join(i + "\n" for i in items) + "    };"

    return (
        "// Generated by `kilnbase gen types`; do not edit.\n\n"
        + JSON_TYPE
        + "\nexport type Database = {\n"
        + f"  {json.dumps(schema)}: {{\n"
        + "\n".join([block("Tables", tables), block("Views", views), block("Enums", enum_lines)])
        + "\n  };\n};\n"
    )


def run(env_file: Path, schema: str, output: Path | None) -> int:
    try:
        meta = query_db(env_file.resolve().parent, META_SQL, schema=schema)
    except (OSError, subprocess.CalledProcessError, json.JSONDecodeError) as e:
        detail = getattr(e, "stderr", None) or e
        print(f"gen types: could not read the database schema: {detail}", file=sys.stderr)
        return 1
    text = render(meta, schema)
    if output is None:
        sys.stdout.write(text)
    else:
        output.write_text(text, encoding="utf-8")
        print(f"gen types: wrote {output}", file=sys.stderr)
    return 0
