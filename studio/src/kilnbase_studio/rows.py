"""SQL for the table editor. Table and column names are only ever ones read back from the catalog
(COLUMNS_SQL), quoted here; values travel as one JSON parameter through json_populate_record, so
Postgres parses them with the column types and defaults still apply to columns left out."""

COLUMNS_SQL = """
select a.attname as name, format_type(a.atttypid, a.atttypmod) as type,
       not a.attnotnull as nullable, pg_get_expr(d.adbin, d.adrelid) as default,
       coalesce(a.attnum = any(i.indkey), false) as primary_key,
       (a.attidentity = 'a' or a.attgenerated <> '') as read_only
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  left join pg_index i on i.indrelid = c.oid and i.indisprimary
 where n.nspname = 'public' and c.relname = $1 and c.relkind in ('r', 'p')
   and a.attnum > 0 and not a.attisdropped
 order by a.attnum
"""


class BadRequest(Exception):
    pass


def ident(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


class Table:
    def __init__(self, name: str, columns: list[dict]):
        self.name = name
        self.relation = f"public.{ident(name)}"
        self.columns = {c["name"]: c for c in columns}
        self.key = [c["name"] for c in columns if c["primary_key"]]

    def _writable(self, values: dict) -> list[str]:
        if not isinstance(values, dict) or not values:
            raise BadRequest("give at least one column value")
        for name in values:
            column = self.columns.get(name)
            if column is None:
                raise BadRequest(f"no column {name!r}")
            if column["read_only"]:
                raise BadRequest(f"{name!r} is generated by the database")
        return list(values)

    def _key_match(self, key: dict, param: int) -> str:
        if not self.key:
            raise BadRequest("this table has no primary key, so its rows cannot be edited here")
        if not isinstance(key, dict) or set(key) != set(self.key):
            raise BadRequest(f"identify the row by its primary key: {', '.join(self.key)}")
        cols = ", ".join(ident(k) for k in self.key)
        return (
            f"({cols}) = (select {cols}"  # noqa: S608
            f" from json_populate_record(null::{self.relation}, ${param}::json))"
        )

    def select(self) -> str:
        order = ", ".join(ident(k) for k in self.key) or "ctid"
        return (
            f"select to_json(t)::text as row from {self.relation} t"  # noqa: S608
            f" order by {order} limit $1 offset $2"
        )

    def insert(self, values: dict) -> str:
        cols = ", ".join(ident(c) for c in self._writable(values))
        return (
            f"insert into {self.relation} as t ({cols})"  # noqa: S608
            f" select {cols} from json_populate_record(null::{self.relation}, $1::json)"
            " returning to_json(t)::text"
        )

    def update(self, key: dict, values: dict) -> str:
        cols = ", ".join(ident(c) for c in self._writable(values))
        return (
            f"update {self.relation} as t set ({cols}) = ("  # noqa: S608
            f"select {cols} from json_populate_record(null::{self.relation}, $1::json))"
            f" where {self._key_match(key, 2)} returning to_json(t)::text"
        )

    def delete(self, key: dict) -> str:
        return (
            f"delete from {self.relation} as t"  # noqa: S608
            f" where {self._key_match(key, 1)} returning to_json(t)::text"
        )
